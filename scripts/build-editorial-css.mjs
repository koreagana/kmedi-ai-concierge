/**
 * kmedispring.com(Editorial 스킨)용 CSS 생성기.
 *
 * 옛 kmedispring.com 레포(koreagana/K-medispring)의 assets/css/main.css(HTML5 UP
 * "Editorial" 템플릿 + 11개월간 쌓인 커스텀)와 Font Awesome CSS를 그대로 가져와서,
 * 모든 셀렉터를 `.ed-skin` 아래로 가둔다. 그래야 같은 앱 안의 기존 스타일(index.css)과
 * 서로 새지 않는다.
 *   - html / body / :root  →  .ed-skin  (body.is-menu-visible → .ed-skin.is-menu-visible)
 *   - 그 외                 →  .ed-skin <원래 셀렉터>
 *   - @font-face: 옛 사이트에서도 실제로는 로드되지 않던 로컬 폰트(../fonts/*)는 버리고,
 *     Font Awesome 웹폰트 경로만 /editorial/webfonts/ 로 바꾼다.
 *
 * 원본은 src/skins/editorial/vendor/ 에 그대로 두고, 이 스크립트로
 * src/skins/editorial/editorial.scoped.css 를 다시 만든다:
 *   node scripts/build-editorial-css.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'

const __dirname = dirname(fileURLToPath(import.meta.url))
const dir = resolve(__dirname, '../src/skins/editorial')
const SCOPE = '.ed-skin'

// 옛 main.css에는 셀렉터 없이 선언만 남은 조각이 하나 있다(브라우저는 무시하고 넘어가지만
// postcss는 파싱 에러). 원래 동작(무시)과 똑같이 여기서 잘라낸다.
function stripOrphanBlock(css) {
  return css.replace(
    /\/\* 본문 중앙 고정 – 현재 크기 유지 \*\/\s*width:100% !important;[\s\S]*?\}/,
    '/* (orphan declarations removed by build-editorial-css) */',
  )
}

function scopeSelector(sel) {
  const s = sel.trim()
  if (!s) return s
  // html, body, :root 로 시작하는 셀렉터 → 스코프 루트 자체
  const m = s.match(/^(html|body|:root)(?![\w-])(.*)$/)
  if (m) {
    const rest = m[2]
    // "html body" / "html > body" 같은 조합
    const inner = rest.replace(/^\s*>?\s*body(?![\w-])/, '')
    return `${SCOPE}${inner}`
  }
  return `${SCOPE} ${s}`
}

function scope(css) {
  const root = postcss.parse(css)
  root.walkAtRules('font-face', (at) => {
    // FA는 src를 두 번 선언한다(IE용 eot 단독 → 전체 목록). 전체 목록에서 woff2만 남긴다
    // (지원 브라우저 전부 커버, public/editorial/webfonts에 woff2만 복사해둠).
    const srcs = at.nodes.filter((n) => n.prop === 'src')
    const woff2 = srcs.map((n) => n.value.match(/([\w-]+\.woff2)/)).find(Boolean)
    if (!woff2 || !srcs.some((n) => /webfonts\//.test(n.value))) { at.remove(); return }
    srcs.slice(1).forEach((n) => n.remove())
    srcs[0].value = `url("/editorial/webfonts/${woff2[1]}") format("woff2")`
  })
  root.walkRules((rule) => {
    const parent = rule.parent
    if (parent && parent.type === 'atrule' && /keyframes$/.test(parent.name)) return
    rule.selectors = [...new Set(rule.selectors.map(scopeSelector))]
  })
  return root.toString()
}

const main = stripOrphanBlock(readFileSync(resolve(dir, 'vendor/editorial-main.css'), 'utf8'))
const fa = readFileSync(resolve(dir, 'vendor/fontawesome-all.min.css'), 'utf8')

const header = `/* AUTO-GENERATED by scripts/build-editorial-css.mjs — 직접 수정하지 말 것.
   원본: src/skins/editorial/vendor/ (HTML5 UP Editorial, CCA 3.0 — html5up.net/license) */\n`
writeFileSync(resolve(dir, 'editorial.scoped.css'), header + scope(fa) + '\n' + scope(main))
console.log('wrote', resolve(dir, 'editorial.scoped.css'))

function translate(text: string, dict: [string, string][]): string {
  const sorted = [...dict].sort((a, b) => b[0].length - a[0].length)
  let out = ''
  let i = 0
  while (i < text.length) {
    const hit = sorted.find(([ko]) => text.startsWith(ko, i))
    if (hit) { out += hit[1]; i += hit[0].length } else { out += text[i]; i += 1 }
  }
  return out
}

